def get_effective_host_sni(server: Server, inbound_item: dict) -> str:
    host = (inbound_item.get("domain_or_ip") or "").strip().lower()
    if not host:
        host = (server.domain_or_ip or "").strip().lower()
    return host


def build_config_name(
    username: str, 
    location_name: str, 
    client_uuid: Optional[str] = None,
    index: Optional[int] = None
) -> str:
    """
    Constructs a unique config name and email:
    - Single config:  {username}-{region}-{short_id}-PAYG
    - Multi-config:   {username}-{region}-{index}-{short_id}-PAYG
    All spaces are replaced with underscores (_).
    """
    clean_username = (username or "user").strip().replace(" ", "_")
    clean_region = (location_name or "Region").strip().replace(" ", "_")
    
    short_id = str(client_uuid).replace("-", "")[:8] if client_uuid else uuid.uuid4().hex[:8]
    
    if index and index > 1:
        return f"{clean_username}-{clean_region}-{index}-{short_id}-PAYG"
    return f"{clean_username}-{clean_region}-{short_id}-PAYG"


async def ensure_config_uri(cfg: UserConfig, db: Session, username: Optional[str] = None) -> str:
    if not username:
        sub = db.query(UserSubscription).filter(UserSubscription.user_id == cfg.user_id).first()
        username = sub.username if (sub and sub.username) else f"usr_{str(cfg.user_id)[:8]}"

    # Use the config's exact unique client_email to preserve distinct multi-config index and short_id
    if cfg.client_email and cfg.client_email.strip():
        config_name = cfg.client_email.strip()
    else:
        loc_name = cfg.location.name if cfg.location else (cfg.server.name if cfg.server else "Region")
        config_name = build_config_name(username, loc_name, cfg.client_uuid)

    # 1. If URI is already stored in DB, ensure its remark tag matches the unique config name
    if cfg.uri and cfg.uri.strip():
        base_link = cfg.uri.strip().split("#")[0]
        return f"{base_link}#{config_name}"

    # 2. If missing, query 3x-ui API directly
    server = cfg.server
    if not server or not getattr(server, "is_reachable", True):
        return ""

    sub_id = cfg.client_uuid.replace("-", "")[:16]
    fetched_uri = await XUIClient.get_client_uri(
        api_url=server.api_url,
        api_token=server.api_token,
        inbound_id=cfg.inbound_id,
        email=cfg.client_email,
        client_uuid=cfg.client_uuid,
        sub_id=sub_id,
        version=getattr(server, "xui_version", "v3.5.0")
    )

    if fetched_uri:
        base_link = fetched_uri.strip().split("#")[0]
        cfg.uri = f"{base_link}#{config_name}"
        db.commit()
        db.refresh(cfg)
        return cfg.uri

    return ""


def get_or_create_sub_token(user_id: uuid.UUID, db: Session) -> UserSubscription:
    """Retrieves or auto-generates a unique 64-character subscription token for a user."""
    sub = db.query(UserSubscription).filter(UserSubscription.user_id == user_id).first()
    if not sub:
        token = uuid.uuid4().hex + uuid.uuid4().hex  # 64 alphanumeric characters
        sub = UserSubscription(user_id=user_id, sub_token=token)
        db.add(sub)
        db.commit()
        db.refresh(sub)
    return sub


